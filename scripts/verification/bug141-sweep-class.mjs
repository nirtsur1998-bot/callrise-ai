/**
 * BUG-141 — apply the collection-time warm-up to the whole CLASS.
 *
 * The class: a test file that imports a module INSIDE a test or hook body, so
 * the first test to reach that import pays a cold fetch/transform from the one
 * vite transform server every worker process shares — inside its own 20 s
 * per-test budget. `vi.resetModules()` clears the executed-module registry but
 * not the fetch cache, which is why only the first test pays and why the
 * failures were always the first `it()` in a file.
 *
 * Seven files were fixed one at a time, each admitted only after it had already
 * produced a timeout. That rule surfaced a NEW file every measurement round —
 * a sampling process, not a queue. The founder's call (2026-09-09): the
 * mechanism belongs to the pattern, not to the files that happened to time out
 * while someone was watching.
 *
 * THE CLASS IS 45 FILES, NOT 132. "132" came from `grep -l "await import("`,
 * which counts files whose import is ALREADY at module scope — i.e. files that
 * already do what this fix does. Depth-aware counting gives: 45 files import a
 * relative module from inside a body; 7 were fixed by hand, 2 are controls, 11
 * already import the same module statically at top level (so warming would be
 * a literal no-op), and 25 need the change.
 *
 * WHAT IT WARMS: every dynamic-import specifier that appears inside a function
 * body, is written as a plain quoted string, is RELATIVE (bare ids are
 * node_modules, not our transform graph), and is not already imported at module
 * scope. It leaves the two untreated CONTROLS alone so the sweep can be
 * measured against something.
 *
 * Usage:
 *   node scripts/verification/bug141-sweep-class.mjs --dry     # list, change nothing
 *   node scripts/verification/bug141-sweep-class.mjs           # apply
 *   node scripts/verification/bug141-sweep-class.mjs --revert  # undo (idempotent)
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const ROOT = process.cwd()
const SRC = join(ROOT, 'src')
const NL = String.fromCharCode(10)

/** Left untreated ON PURPOSE so the sweep has a control at scale. If these two
 *  still sit at ~5 s after the sweep while everything else collapses, that is
 *  the same control logic that made each per-file round a measurement. */
const CONTROLS = ['catalog-ipc.test.ts', 'catalogIpc.assistantChat.test.ts']

const MARK_START = '// --- BUG-141 collection-time warm-up (generated) ---'
const MARK_END = '// --- end BUG-141 warm-up ---'

const HEADER = [
  MARK_START,
  "// Pull these graphs through vite's transform pipeline HERE, at collection",
  '// time, where no per-test timeout applies. Without it the first it() to',
  '// import one pays the COLD fetch inside its own 20 s budget, from a pipeline',
  '// shared by every worker process in the run — a queue on a serialized',
  '// resource, which is why it stalled rather than slowed. See BUG-141.',
  '//',
  '// Two limits, spelled out in full at the same block in',
  '// src/main/assistant/__tests__/assistant-ipc.turn.test.ts: this makes NOTHING',
  '// faster (it stops shared-infrastructure latency being billed to a per-test',
  '// budget), and collection has no timeout, so a genuinely hung fetch now hangs',
  '// the file instead of failing one test.',
  '//',
  '// Generated by scripts/verification/bug141-sweep-class.mjs — re-run that',
  '// rather than editing this block by hand.'
]

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p, out)
    else if (name.endsWith('.test.ts')) out.push(p)
  }
  return out
}

/**
 * Depth-aware scan: whether an import is at module scope or inside a body is
 * decided by BRACE DEPTH.
 *
 * The first version used a line-anchored regex for the top-level set, and that
 * matched an INDENTED body import too — so every file looked as though it
 * already warmed what it lazily imports, and the sweep reported 0 files to
 * change. A sweep that reports "nothing to do" is exactly the clean-looking
 * zero that has to be checked before it is believed. This one was, and it was
 * wrong.
 */
export function scan(text) {
  const topLevel = new Set()
  const body = new Set()
  let depth = 0
  let inBlock = false
  for (const raw of text.split(NL)) {
    let line = raw
    if (inBlock) {
      const e = line.indexOf('*/')
      if (e < 0) continue
      line = line.slice(e + 2)
      inBlock = false
    }
    const b = line.indexOf('/*')
    if (b >= 0 && line.indexOf('*/', b) < 0) {
      inBlock = true
      line = line.slice(0, b)
    }
    const c = line.indexOf('//')
    const code = c >= 0 ? line.slice(0, c) : line

    const target = depth === 0 ? topLevel : body
    for (const m of code.matchAll(/\bimport\(\s*(['"])([^'"]+)\1\s*\)/g)) target.add(m[2])
    for (const m of code.matchAll(/^\s*import\s.*?from\s+(['"])([^'"]+)\1/g)) topLevel.add(m[2])

    // Count braces on the code with STRING LITERALS AND REGEXES REMOVED.
    // Counting them raw makes depth drift on any line holding a `${...}`
    // template, a regex like /\{/, or a brace inside a quoted string — and a
    // drifted depth silently reclassifies a body import as top-level, so the
    // file is skipped and the sweep under-applies while looking complete.
    // Two files (crmnote-contactintel-signal-plumbing, isolation-and-beta)
    // were missed exactly this way before this line existed.
    const bare = code
      .replace(/\\./g, '')
      .replace(/'[^']*'/g, "''")
      .replace(/"[^"]*"/g, '""')
      .replace(/`[^`]*`/g, '``')
    depth += (bare.match(/\{/g) ?? []).length - (bare.match(/\}/g) ?? []).length
    if (depth < 0) depth = 0
  }
  return { topLevel, body }
}

/** Last line of the module-scope prologue: imports, vi.mock/vi.hoisted blocks,
 *  and top-level `await import(...)`. The block goes straight after it, so it
 *  runs with every mock already registered and before any other code. */
function prologueEnd(lines) {
  let last = -1
  let depth = 0
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i]
    const opensHere =
      depth === 0 &&
      /^(import\s|import\(|await import\(|vi\.mock\(|vi\.unmock\(|vi\.hoisted\(|(?:const|let|var)\s.*=\s*(?:await\s+)?(?:vi\.hoisted\(|import\())/.test(
        l
      )
    if (opensHere) last = i
    depth += (l.match(/[({[]/g) ?? []).length - (l.match(/[)}\]]/g) ?? []).length
    if (depth < 0) depth = 0
    if (depth > 0 && opensHere) {
      let j = i
      let d = depth
      while (j + 1 < lines.length && d > 0) {
        j++
        d += (lines[j].match(/[({[]/g) ?? []).length - (lines[j].match(/[)}\]]/g) ?? []).length
      }
      last = j
      i = j
      depth = 0
    }
  }
  return last
}

/**
 * RUN-ONLY-WHEN-RUN. Without this guard the file rewrites 23 test files as a
 * SIDE EFFECT OF BEING IMPORTED — which is how it got applied twice by
 * accident on 2026-09-09, from `await import(…)` in a one-liner that only
 * wanted `scan()` for a spot check. A module whose import mutates the
 * working tree is a trap for exactly the person trying to inspect it.
 */
const RAN_DIRECTLY =
  process.argv[1] &&
  import.meta.url.endsWith(process.argv[1].split('\\').join('/').split('/').pop())
if (!RAN_DIRECTLY) {
  // imported for `scan()` — export and do nothing else
} else {
  main()
}

function main() {
  const mode = process.argv.includes('--revert')
    ? 'revert'
    : process.argv.includes('--dry')
      ? 'dry'
      : 'apply'

  let changed = 0
  let skipped = 0
  const report = []

  for (const file of walk(SRC)) {
    const rel = relative(ROOT, file).split('\\').join('/')
    const text = readFileSync(file, 'utf8')
    const crlf = text.includes('\r\n')
    const body = crlf ? text.split('\r\n').join(NL) : text
    const save = (s) => writeFileSync(file, crlf ? s.split(NL).join('\r\n') : s, 'utf8')

    const has = body.includes(MARK_START)
    if (mode === 'revert') {
      if (!has) continue
      const lines = body.split(NL)
      const out = []
      let dropping = false
      for (const l of lines) {
        if (l === MARK_START) {
          dropping = true
          if (out.length && out[out.length - 1] === '') out.pop()
          continue
        }
        if (l === MARK_END) {
          dropping = false
          continue
        }
        if (!dropping) out.push(l)
      }
      save(out.join(NL))
      changed++
      continue
    }
    if (has) continue

    if (CONTROLS.some((c) => rel.endsWith('/' + c))) {
      report.push(`CONTROL, left untreated on purpose: ${rel}`)
      skipped++
      continue
    }
    if (body.includes('BUG-141 — WARM THE MODULE GRAPH HERE')) {
      report.push(`already warmed by hand: ${rel}`)
      skipped++
      continue
    }

    const { topLevel, body: lazy } = scan(body)
    const specs = [...lazy].filter((s) => s.startsWith('.') && !topLevel.has(s))
    if (!specs.length) continue

    const lines = body.split(NL)
    const at = prologueEnd(lines)
    if (at < 0) {
      report.push(`NO SAFE INSERT POINT, skipped: ${rel}`)
      skipped++
      continue
    }
    lines.splice(at + 1, 0, '', ...HEADER, ...specs.map((s) => `await import('${s}')`), MARK_END)
    if (mode === 'apply') save(lines.join(NL))
    report.push(
      `${mode === 'dry' ? 'WOULD WARM' : 'warmed'} ${rel} (${specs.length}): ${specs.join(', ')}`
    )
    changed++
  }

  for (const r of report) console.log(r)
  console.log(`${NL}${mode}: ${changed} file(s) changed, ${skipped} skipped`)
}
